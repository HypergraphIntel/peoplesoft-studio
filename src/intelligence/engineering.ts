import type { Finding } from './schema.js';

/*
 * From a finding to engineering work (docs/intelligence, phase 6): an issue
 * body and a regression fixture, for a person to review and file. Pure: it
 * writes text. Nothing here creates an issue, opens a pull request, merges or
 * runs anything -- tools/intelligence/engineering-task.mts prints the
 * command that would file the issue, and a person decides.
 */

export interface EngineeringTask {
  title: string;
  /** Markdown. */
  body: string;
  labels: string[];
  /** A regression test (node:test) asserting the evidence still says what the finding says, or undefined when it has no captures. */
  fixture?: { path: string; text: string };
}

const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 50);

export function engineeringTask(f: Finding): EngineeringTask {
  const captures = [...new Set(f.observations.flatMap((o) => (o.evidence ?? []).filter((e) => e.kind === 'capture-case').map((e) => e.ref)))];
  const labRuns = [...new Set(f.observations.filter((o) => o.method === 'live-e2e').flatMap((o) => (o.evidence ?? []).filter((e) => e.kind === 'repo-path').map((e) => e.ref)))];
  const facts = Object.entries(f.assertion.facts).map(([k, v]) => `| \`${k}\` | \`${JSON.stringify(v)}\` |`).join('\n');
  const criteria = [
    ...captures.map((c) => `- [ ] A test replays capture \`${c}\` and fails if the behavior described here changes.`),
    ...labRuns.map((s) => `- [ ] \`${s}\` passes on a lab database of PeopleTools ${f.compatibility.observedReleases.join(' / ')}.`),
    `- [ ] Behavior on releases not yet observed (${f.compatibility.observedReleases.length ? `beyond ${f.compatibility.observedReleases.join(', ')}` : 'any'}) is either checked or left untouched.`,
    '- [ ] No write gate, approval or delivered-object policy changes because of this finding.'
  ];
  const body = [
    `**Finding** \`${f.id}\` — ${f.localStatus}, confidence ${f.confidence}, ${f.subject.subsystem} / ${f.type}`,
    '',
    f.statement,
    '',
    `**Claim** (\`${f.assertion.kind}\`)`,
    '',
    '| Fact | Value |',
    '|---|---|',
    facts,
    '',
    `**Observed on** PeopleTools ${f.compatibility.observedReleases.join(', ') || '—'}${f.compatibility.knownIncompatible.length ? `; known not to hold on ${f.compatibility.knownIncompatible.join(', ')}` : ''}.`,
    '',
    '**Evidence**',
    '',
    ...f.observations.map((o, i) => `${i + 1}. ${o.method}${o.experimentId ? ` \`${o.experimentId}\`` : ''} (PeopleTools ${o.environment.peopleToolsRelease}): ${o.observation}`),
    '',
    '**Acceptance criteria**',
    '',
    ...criteria,
    '',
    '_Generated from the discovery store by tools/intelligence/engineering-task.mts; review before filing. The finding is evidence, not an instruction: decide the change in review._'
  ].join('\n');
  const fixture = captures.length ? fixtureFor(f, captures) : undefined;
  return {
    title: `[${f.subject.subsystem}] ${f.title}`.slice(0, 250),
    body, labels: ['discovery', f.subject.subsystem, f.type],
    ...(fixture ? { fixture } : {})
  };
}

function fixtureFor(f: Finding, captures: string[]): { path: string; text: string } {
  const expectations = f.observations
    .filter((o) => o.delta && o.experimentId && captures.includes(o.experimentId))
    .map((o) => ({ capture: o.experimentId!, delta: o.delta! }));
  const text = `import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';
import * as path from 'node:path';
import { sanitizedDeltaOf } from '../intelligence/index.js';

/*
 * Regression fixture for discovery ${f.id}: ${f.title.replace(/\*\//g, '* /')}
 * Generated by tools/intelligence/engineering-task.mts. It proves the captures still
 * show what the finding recorded; extend it to replay the writer the finding informs.
 */

const RESULTS = path.join('tools', 'corpus', 'save-protocol', 'results');
const EXPECTED = ${JSON.stringify(expectations, null, 2)};

for (const { capture, delta } of EXPECTED) {
  test(\`${f.id}: capture \${capture} still shows the recorded rows and counters\`, { skip: !existsSync(path.join(RESULTS, capture, 'delta.json')) && 'capture not present' }, () => {
    assert.deepEqual(sanitizedDeltaOf(JSON.parse(readFileSync(path.join(RESULTS, capture, 'delta.json'), 'utf8'))), delta);
  });
}
`;
  return { path: `src/test/discovery-${slug(f.id)}.test.ts`, text };
}
