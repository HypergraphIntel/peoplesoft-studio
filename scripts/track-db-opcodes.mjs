// Generates docs/unmapped-opcodes.md from a scripts/scan-db-opcodes.mjs
// report: every opcode the decoder still doesn't recognise anywhere in
// the live database, sorted by its single cleanest sample (lowest
// total-unmapped-count program it appears in) so the next investigation
// pass has the best hand-walking candidate for each one, not just a
// raw occurrence count.
//
// Usage: node scripts/track-db-opcodes.mjs <db-scan.json> docs/unmapped-opcodes.md
import { readFileSync, writeFileSync } from 'node:fs';

const report = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const OUT = process.argv[3];

const rows = report.opcodes.map((o) => {
  const samples = [...o.samples].sort((a, b) => a.totalUnmapped - b.totalUnmapped);
  return { opcode: o.opcode, count: o.count, samples };
});
rows.sort((a, b) => a.samples[0].totalUnmapped - b.samples[0].totalUnmapped);

const lines = [];
lines.push('# Unmapped opcode tracker');
lines.push('');
lines.push('Generated by `scripts/track-db-opcodes.mjs` from a full scan of the live');
lines.push('database (`scripts/scan-db-opcodes.mjs`), not just the 204-program');
lines.push('calibration corpus -- see docs/ROADMAP.md pass thirty-nine. Not narrative');
lines.push('(see `docs/ROADMAP.md` for that) -- a working list of every opcode the');
lines.push('decoder does not yet recognise anywhere in the database, so the next');
lines.push('investigation pass has real byte-for-byte samples to start from.');
lines.push('Regenerate after any decoder change or database rescan:');
lines.push('`node scripts/scan-db-opcodes.mjs <out.json> && node scripts/track-db-opcodes.mjs <out.json> docs/unmapped-opcodes.md`.');
lines.push('');
lines.push(`Scanned ${report.programCount} programs (${report.cleanCount} clean, ` +
  `${report.brokenCount} broken/incomplete), ${report.totalUnmapped} unmapped ` +
  `opcode occurrences total across ${rows.length} distinct opcodes.`);
lines.push('');
lines.push('Sorted by each opcode\'s own single cleanest sample (lowest total-unmapped-');
lines.push('count program it occurs in, ascending) -- the opcodes at the top are the');
lines.push('best next candidates, the same corruption-noise-filtering discipline every');
lines.push('corpus pass has used throughout. None of these occur anywhere in the');
lines.push('204-program corpus itself (otherwise the corpus tooling would already have');
lines.push('caught them) -- confirming one requires hand-walking real database bytes');
lines.push('directly, structurally rather than against known-correct source, the way');
lines.push('pass thirty-nine did for 0x20/0x51/0x60.');
lines.push('');
lines.push('| opcode | occurrences | cleanest sample | offset | that program\'s total unmapped |');
lines.push('|---|---|---|---|---|');
for (const r of rows) {
  const best = r.samples[0];
  lines.push(`| ${r.opcode} | ${r.count} | ${best.key} | ${best.offset} | ${best.totalUnmapped} |`);
}
lines.push('');

writeFileSync(OUT, lines.join('\n'));
console.log(`wrote ${OUT}: ${rows.length} distinct unmapped opcodes`);
